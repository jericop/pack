package multiplatform

import (
	"fmt"
	"strings"
)

// GenerateDockerfile produces a Dockerfile that runs the lifecycle phases for a single platform.
// It uses BuildKit features: --mount=type=cache for lifecycle caching and --mount=type=secret
// for registry credentials.
func GenerateDockerfile(opts PlatformBuildOpts) string {
	var b strings.Builder

	b.WriteString("# syntax=docker/dockerfile:1\n")
	b.WriteString("# Generated by pack for multi-platform build\n")
	b.WriteString(fmt.Sprintf("# Platform: %s\n", opts.Platform.String()))
	b.WriteString("\n")

	// Multi-stage: pull lifecycle image if specified (for untrusted builders)
	if opts.LifecycleImage != "" {
		b.WriteString(fmt.Sprintf("FROM %s AS lifecycle\n", opts.LifecycleImage))
		b.WriteString("\n")
	}

	// Main build stage from the builder image
	b.WriteString(fmt.Sprintf("FROM %s\n", opts.BuilderImage))
	b.WriteString("USER root\n")
	b.WriteString("\n")

	// Copy lifecycle binaries if using a separate lifecycle image
	if opts.LifecycleImage != "" && !strings.HasPrefix(opts.LifecycleImage, "pack.local/") {
		b.WriteString("COPY --from=lifecycle /cnb/lifecycle /cnb/lifecycle\n")
		b.WriteString("\n")
	}

	// Set up directories and permissions
	b.WriteString("RUN mkdir -p /cache && chown -R ")
	b.WriteString(fmt.Sprintf("%d:%d", opts.BuilderUID, opts.BuilderGID))
	b.WriteString(" /cache\n")
	b.WriteString("\n")

	// Set environment variables
	b.WriteString(fmt.Sprintf("ENV CNB_PLATFORM_API=%s\n", opts.PlatformAPI))
	b.WriteString("\n")

	// Switch to CNB user for app copy and lifecycle execution
	b.WriteString(fmt.Sprintf("USER %d:%d\n", opts.BuilderUID, opts.BuilderGID))
	b.WriteString("\n")

	// Copy app source into workspace
	b.WriteString("COPY --chown=")
	b.WriteString(fmt.Sprintf("%d:%d", opts.BuilderUID, opts.BuilderGID))
	b.WriteString(" . /workspace\n")
	b.WriteString("WORKDIR /workspace\n")
	b.WriteString("\n")

	// Generate the RUN instruction(s) for lifecycle phases
	b.WriteString(generateLifecycleRun(opts))

	return b.String()
}

// generateLifecycleRun produces the RUN instruction(s) that execute the lifecycle phases.
// All phases that share the cache mount are combined into a single RUN to share filesystem state.
func generateLifecycleRun(opts PlatformBuildOpts) string {
	var b strings.Builder

	// Determine mounts needed
	mounts := buildMounts(opts)

	// Build a single heredoc RUN command that executes all phases in sequence.
	// This keeps them in a single layer so filesystem state (/layers, /workspace)
	// is shared between phases without needing volumes.
	b.WriteString("RUN ")
	if len(mounts) > 0 {
		for _, m := range mounts {
			b.WriteString(m)
			b.WriteString(" \\\n    ")
		}
	}
	b.WriteString("/bin/bash <<'LIFECYCLE_EOF'\n")
	b.WriteString("set -euo pipefail\n")
	b.WriteString("\n")

	// Write each phase as a command
	for i, phase := range opts.Phases {
		// Add a comment header for readability
		b.WriteString(fmt.Sprintf("# Phase: %s\n", phase.Name))

		// Set per-phase environment variables
		for k, v := range phase.Env {
			b.WriteString(fmt.Sprintf("export %s=%q\n", k, v))
		}

		// Write the command
		b.WriteString(strings.Join(phase.Command(), " "))
		b.WriteString("\n")

		// Add spacing between phases
		if i < len(opts.Phases)-1 {
			b.WriteString("\n")
		}
	}

	b.WriteString("LIFECYCLE_EOF\n")

	return b.String()
}

// buildMounts returns the --mount flags needed for the RUN instruction.
func buildMounts(opts PlatformBuildOpts) []string {
	var mounts []string

	// Check if any phase needs the cache
	needsCache := false
	for _, p := range opts.Phases {
		if p.NeedsCache {
			needsCache = true
			break
		}
	}

	// Check if any phase needs registry auth
	needsAuth := false
	for _, p := range opts.Phases {
		if p.NeedsRegistryAuth {
			needsAuth = true
			break
		}
	}

	// Persistent cache mount for lifecycle buildpack layer caching
	if needsCache && opts.CacheID != "" {
		mounts = append(mounts, fmt.Sprintf(
			"--mount=type=cache,id=%s,target=/cache,uid=%d,gid=%d",
			opts.CacheID, opts.BuilderUID, opts.BuilderGID,
		))
	}

	// Secret mount for registry credentials
	if needsAuth && opts.DockerConfigPath != "" {
		mounts = append(mounts, fmt.Sprintf(
			"--mount=type=secret,id=docker-config,target=/home/cnb/.docker/config.json",
		))
	}

	return mounts
}

// GenerateDockerfileMultiPlatform produces a Dockerfile for multi-platform builds.
// It uses the BuildKit built-in ARG TARGETARCH to scope the cache mount per architecture,
// ensuring amd64 and arm64 builds don't share lifecycle cache state.
// This Dockerfile is used with `docker buildx build --platform linux/amd64,linux/arm64`
// so buildkit runs it once per platform in parallel.
func GenerateDockerfileMultiPlatform(opts PlatformBuildOpts) string {
	var b strings.Builder

	b.WriteString("# syntax=docker/dockerfile:1\n")
	b.WriteString("# Generated by pack for multi-platform build\n")
	b.WriteString("\n")

	// Multi-stage: pull lifecycle image if specified (for untrusted builders)
	// Skip pack.local/ images as they are ephemeral and only exist in the local daemon
	if opts.LifecycleImage != "" && !strings.HasPrefix(opts.LifecycleImage, "pack.local/") {
		b.WriteString(fmt.Sprintf("FROM %s AS lifecycle\n", opts.LifecycleImage))
		b.WriteString("\n")
	}

	// Multi-stage: pull each additional buildpack image so we can COPY their contents
	for i, bpImage := range opts.BuildpackImages {
		b.WriteString(fmt.Sprintf("FROM %s AS buildpack-%d\n", bpImage, i))
	}
	if len(opts.BuildpackImages) > 0 {
		b.WriteString("\n")
	}

	// Main build stage from the builder image
	b.WriteString(fmt.Sprintf("FROM %s\n", opts.BuilderImage))
	b.WriteString("USER root\n")
	b.WriteString("\n")

	// Copy lifecycle binaries if using a separate lifecycle image
	if opts.LifecycleImage != "" && !strings.HasPrefix(opts.LifecycleImage, "pack.local/") {
		b.WriteString("COPY --from=lifecycle /cnb/lifecycle /cnb/lifecycle\n")
		b.WriteString("\n")
	}

	// Copy buildpack layers from their respective images
	for i := range opts.BuildpackImages {
		b.WriteString(fmt.Sprintf("COPY --from=buildpack-%d /cnb/buildpacks /cnb/buildpacks\n", i))
	}
	if len(opts.BuildpackImages) > 0 {
		b.WriteString("\n")
	}

	// If a custom order.toml is provided, write it into the builder
	if opts.OrderToml != "" {
		// Write order.toml via a heredoc RUN
		b.WriteString("RUN /bin/bash <<'ORDER_EOF'\n")
		b.WriteString("cat > /cnb/order.toml << 'TOML'\n")
		b.WriteString(opts.OrderToml)
		b.WriteString("\nTOML\n")
		b.WriteString("ORDER_EOF\n")
		b.WriteString("\n")
	}

	// Use TARGETARCH (built-in BuildKit ARG) for per-platform cache scoping
	b.WriteString("ARG TARGETARCH\n")
	b.WriteString("\n")

	// Set up directories and permissions
	b.WriteString("RUN mkdir -p /cache /output && chown -R ")
	b.WriteString(fmt.Sprintf("%d:%d", opts.BuilderUID, opts.BuilderGID))
	b.WriteString(" /cache /output\n")
	b.WriteString("\n")

	// Set environment variables
	b.WriteString(fmt.Sprintf("ENV CNB_PLATFORM_API=%s\n", opts.PlatformAPI))
	if opts.ExportMode == ExportOCILayout {
		b.WriteString("ENV CNB_EXPERIMENTAL_MODE=warn\n")
	}
	b.WriteString("\n")

	// Switch to CNB user for app copy and lifecycle execution
	b.WriteString(fmt.Sprintf("USER %d:%d\n", opts.BuilderUID, opts.BuilderGID))
	b.WriteString("\n")

	// Copy app source into workspace
	b.WriteString("COPY --chown=")
	b.WriteString(fmt.Sprintf("%d:%d", opts.BuilderUID, opts.BuilderGID))
	b.WriteString(" . /workspace\n")
	b.WriteString("WORKDIR /workspace\n")
	b.WriteString("\n")

	// Generate the RUN instruction(s) for lifecycle phases
	b.WriteString(generateLifecycleRunMultiPlatform(opts))

	return b.String()
}

// generateLifecycleRunMultiPlatform produces RUN instructions with phase isolation.
// Each lifecycle phase gets its own RUN command for clear progress output.
// Phases are split by credential requirements:
//   - Phases needing registry auth (analyzer, exporter) get --mount=type=secret
//   - Phases running buildpack code (detector, builder) do NOT get credentials
func generateLifecycleRunMultiPlatform(opts PlatformBuildOpts) string {
	var b strings.Builder

	cacheMount := fmt.Sprintf(
		"--mount=type=cache,id=%s-${TARGETARCH},target=/cache,uid=%d,gid=%d",
		opts.CacheID, opts.BuilderUID, opts.BuilderGID,
	)
	secretMount := "--mount=type=secret,id=docker-config,target=/home/cnb/.docker/config.json"

	// When ClearCache is set, skip the persistent cache mount entirely.
	if opts.ClearCache {
		cacheMount = ""
	}

	for _, phase := range opts.Phases {
		// Determine which mounts this phase needs
		var mounts []string
		if phase.NeedsCache || phase.Name == "restorer" || phase.Name == "exporter" {
			if cacheMount != "" {
				mounts = append(mounts, cacheMount)
			}
		}
		// In OCI layout mode, only the exporter doesn't need registry access
		// (it writes to local disk). The analyzer still needs it to read the run image.
		if phase.NeedsRegistryAuth {
			if opts.ExportMode == ExportOCILayout && phase.Name == "exporter" {
				// Exporter in OCI layout mode writes locally, no creds needed
			} else {
				mounts = append(mounts, secretMount)
			}
		}

		// Build the command, substituting image name with per-arch tag where needed
		// and stripping cache args when ClearCache is set
		args := phase.Command()
		if opts.ClearCache {
			args = removeCacheArgs(args)
		}

		// In OCI layout mode, modify analyzer and exporter to use -layout -layout-dir
		if opts.ExportMode == ExportOCILayout {
			args = convertToOCILayoutArgs(args, phase.Name, opts.ImageName)
		} else {
			// Registry mode: use ephemeral per-arch tag so parallel builds don't overwrite each other
			for i, arg := range args {
				if arg == opts.ImageName {
					args[i] = fmt.Sprintf("%s-build-%s-${TARGETARCH}", opts.ImageName, opts.BuildID)
				}
			}
		}

		cmd := strings.Join(args, " ")

		// Write the RUN instruction
		b.WriteString("RUN ")
		if len(mounts) > 0 {
			for _, m := range mounts {
				b.WriteString(m)
				b.WriteString(" \\\n    ")
			}
		}
		b.WriteString(cmd)
		b.WriteString("\n\n")
	}

	return b.String()
}

// filterPhases returns only the phases whose names match the given list.
func filterPhases(phases []PhaseCommand, names ...string) []PhaseCommand {
	nameSet := make(map[string]bool, len(names))
	for _, n := range names {
		nameSet[n] = true
	}
	var result []PhaseCommand
	for _, p := range phases {
		if nameSet[p.Name] {
			result = append(result, p)
		}
	}
	return result
}

// removeCacheArgs strips -cache-dir and its value from a command argument list.
func removeCacheArgs(args []string) []string {
	var result []string
	for i := 0; i < len(args); i++ {
		if args[i] == "-cache-dir" {
			i++ // skip the next arg (the path value)
			continue
		}
		result = append(result, args[i])
	}
	return result
}

// layoutPath converts an image reference to the path format used by OCI layout directories.
// e.g., "docker.io/paketobuildpacks/run:latest" → "docker.io/paketobuildpacks/run/latest"
func layoutPath(imageRef string) string {
	// Replace the tag separator : with / for the layout path
	// registry/repo:tag → registry/repo/tag
	parts := strings.SplitN(imageRef, ":", 2)
	if len(parts) == 2 {
		return parts[0] + "/" + parts[1]
	}
	return imageRef + "/latest"
}

// convertToOCILayoutArgs modifies lifecycle phase args for OCI layout export mode.
// The analyzer gets -layout -layout-dir /output to write the run image reference in layout format.
// The exporter gets -layout -layout-dir /output to write the final image as OCI layout.
// A pre-pull step is added in the Dockerfile to fetch the run image into the layout dir.
func convertToOCILayoutArgs(args []string, phaseName string, imageName string) []string {
	switch phaseName {
	case "analyzer":
		// Insert -layout -layout-dir /output after the binary name
		var result []string
		result = append(result, args[0]) // binary
		result = append(result, "-layout", "-layout-dir", "/output")
		result = append(result, args[1:]...)
		return result
	case "exporter":
		// Insert -layout -layout-dir /output after the binary name
		var result []string
		result = append(result, args[0]) // binary
		result = append(result, "-layout", "-layout-dir", "/output")
		result = append(result, args[1:]...)
		return result
	default:
		return args
	}
}
